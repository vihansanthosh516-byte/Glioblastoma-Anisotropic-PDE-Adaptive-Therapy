#!/usr/bin/env python3
"""
Phase 10: FNO inference timing on a seeded random tensor.

No finite-difference solver or clinical/control workload is run. This measures
latency only, not forecast accuracy, PDE equivalence, speedup, or real-time safety.
Output when explicitly run: output/fno_benchmark.json (not generated by this audit).
"""
import torch
import time
import numpy as np
from pathlib import Path
import sys
import json
import hashlib

sys.path.insert(0, str(Path(__file__).parent))
from fno_solver import FNO3d

PROJECT_ROOT = Path(__file__).resolve().parents[2]


def benchmark_fno(
    model_path=PROJECT_ROOT / "output" / "fno_model.pth",
    grid_size=64,
    n_runs=10,
    device=None,
    seed=42,
    output_path=PROJECT_ROOT / "output" / "fno_benchmark.json",
):
    if n_runs < 1:
        raise ValueError("n_runs must be positive")
    model_path, output_path = Path(model_path), Path(output_path)
    if not model_path.is_absolute():
        model_path = PROJECT_ROOT / model_path
    if not output_path.is_absolute():
        output_path = PROJECT_ROOT / output_path
    if output_path.exists():
        raise FileExistsError(f"Refusing to overwrite prior benchmark: {output_path}")
    torch.manual_seed(seed)
    device = device or ("cuda" if torch.cuda.is_available() else "cpu")
    print(f"[Benchmark] Device: {device}")
    is_cuda = torch.device(device).type == "cuda"

    # Load trained FNO
    checkpoint = torch.load(model_path, map_location=device)
    state_dict = checkpoint["model_state"] if "model_state" in checkpoint else checkpoint
    
    model = FNO3d(in_channels=2, out_channels=1, modes=8, width=20).to(device)
    model.load_state_dict(state_dict)
    model.eval()

    # Create test input
    batch_size = 1
    x = torch.randn(batch_size, 2, grid_size, grid_size, grid_size, device=device)

    # Warmup
    with torch.no_grad():
        for _ in range(3):
            _ = model(x)

    # Benchmark FNO
    torch.cuda.synchronize() if is_cuda else None
    start = time.perf_counter()
    for _ in range(n_runs):
        with torch.no_grad():
            _ = model(x)
    torch.cuda.synchronize() if is_cuda else None
    fno_time = (time.perf_counter() - start) / n_runs

    print(f"[Benchmark] FNO inference: {fno_time*1000:.2f} ms per forward pass ({grid_size}^3 grid)")

    result = {
        "label": "Inference timing on synthetic random tensor; no FD comparator, accuracy or clinical-control validation",
        "fno_time_ms": fno_time * 1000,
        "fd_estimate_s": None,
        "speedup": None,
        "seed": seed,
        "device": str(device),
        "input_shape": list(x.shape),
        "n_runs": n_runs,
        "checkpoint_sha256": hashlib.sha256(model_path.read_bytes()).hexdigest(),
    }
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(result, indent=2), encoding="utf-8")
    if output_path.stat().st_size == 0:
        raise RuntimeError(f"Empty benchmark artifact: {output_path}")
    return result


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="Measure seeded synthetic-tensor FNO inference latency only")
    parser.add_argument("--model", type=str, default=str(PROJECT_ROOT / "output/fno_model.pth"))
    parser.add_argument("--grid", type=int, default=64)
    parser.add_argument("--runs", type=int, default=10)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--output", type=str, default=str(PROJECT_ROOT / "output/fno_benchmark.json"))
    args = parser.parse_args()

    benchmark_fno(model_path=args.model, grid_size=args.grid, n_runs=args.runs,
                  seed=args.seed, output_path=args.output)
