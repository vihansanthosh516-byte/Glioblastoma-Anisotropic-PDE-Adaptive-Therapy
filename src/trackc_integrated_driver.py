"""Integrated Track A/B-inspired -> Track C driver (development; gated).

Connects the tracks only through explicit simulated assumptions: molecular-like and
MRI-like signals are generated by `trackc_integrated_signal_model` from the
simulator's latent f0 under declared (q, a, b, d). No patient data is read. Track A
and Track B supply motivation only (configs/trackABC_integrated_v2.json input_rules).

Modes
- "mechanics": runs schedule preflight, input preparation, prior and arm-plan checks,
  and a caller-supplied stub benchmark. The real policy benchmark is refused, so no
  policy utility is computed.
- "evaluation": refuses unless every evaluation gate in the config is cleared. On the
  current config it always refuses (interval method, precision, seed table, runtime,
  driver review are open).

Shared scenarios: every arm in a world sees the same virtual patients, latent
parameters, signals, scans, and noise (run_shared_policy_world). Controls required in
the arm plan: matched d=0 minimax, molecular-only and MRI-only minimax, no-signal MPC.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path

from trackc_filter_priors import PF_PRIOR_INTEGRATED_V3
from trackc_world_runner import execute_prepared_world, prepare_synthetic_world
from trackc_world_schedule import POLICY_ROLES, SCENARIO_ROLES, validate_development_schedule

PROJECT_ROOT = Path(__file__).resolve().parent.parent
CONFIG_PATH = PROJECT_ROOT / "configs" / "trackABC_integrated_v2.json"

PRIMARY_ARMS = ("finite_set_minimax_mpc", "finite_set_d0_minimax_mpc")
REQUIRED_CONTROL_ARMS = ("finite_set_minimax_molecular_only_mpc", "finite_set_minimax_mri_only_mpc", "no_signal_mpc")


class EvaluationBlocked(PermissionError):
    """Raised when confirmatory evaluation is requested before its gates pass."""


def load_config(path=CONFIG_PATH) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


@dataclass(frozen=True)
class DriverProtocol:
    stop_endpoint: str
    scan_interval_days: int
    particles: int
    forecast_cycles: int
    prior_version: str
    precision_half_width_days: float
    open_gates: tuple

    @property
    def scan_every_cycles(self) -> int:
        return self.scan_interval_days // 28


def load_protocol(config=None) -> DriverProtocol:
    """Read run settings from the config at run time (gap C8: config was not loaded by code)."""
    c = load_config() if config is None else config
    prior = c["particle_filter_prior"]
    if prior.get("version") != "PF_PRIOR_INTEGRATED_V3":
        raise ValueError("config particle_filter_prior must be PF_PRIOR_INTEGRATED_V3")
    for key, (lo, hi) in (("r_day_minus1_log_uniform", PF_PRIOR_INTEGRATED_V3["r"][:2]),
                          ("B0_uniform", PF_PRIOR_INTEGRATED_V3["B0"][:2])):
        if tuple(prior[key]) != (lo, hi):
            raise ValueError(f"config prior {key} does not match the code constant")
    clock = c["simulation_clock_and_treatment"]
    ctrl = c["controller_comparison"]
    precision = _find_precision(c["outcomes_and_inference"])
    return DriverProtocol(
        stop_endpoint=_stop_endpoint(c),
        scan_interval_days=int(clock["scan_interval_primary_days"]),
        particles=int(ctrl["particle_filters"]),
        forecast_cycles=int(ctrl["forecast_cycles"]),
        prior_version=prior["version"],
        precision_half_width_days=precision,
        open_gates=tuple(c.get("not_yet_locked_before_evaluation", ())),
    )


def _find_precision(block) -> float:
    return float(block["precision_target_half_width_days"])


def _stop_endpoint(c) -> str:
    return str(c["simulation_clock_and_treatment"]["stop_endpoint_code"])


def check_evaluation_gates(protocol: DriverProtocol) -> None:
    """Refuse confirmatory evaluation while any declared gate is open. Never relaxes a gate."""
    if protocol.open_gates:
        raise EvaluationBlocked("evaluation refused; open gates: " + "; ".join(protocol.open_gates))
    if protocol.precision_half_width_days != 14.0:
        raise EvaluationBlocked("precision target differs from the unchanged 14-day rule")


def build_world_schedule(n_worlds: int, *, scenario_base: int, policy_base: int, prefix: str) -> list[dict]:
    """Deterministic schedule: 6 scenario-stream and 5 policy-stream seeds per world.

    Scenario and policy seeds come from separate contiguous blocks so they never
    collide numerically. The caller must reserve both blocks in the seed registry.
    """
    if n_worlds < 1:
        raise ValueError("n_worlds must be positive")
    ns, npol = len(SCENARIO_ROLES), len(POLICY_ROLES)
    if not (policy_base >= scenario_base + n_worlds * ns or scenario_base >= policy_base + n_worlds * npol):
        raise ValueError("scenario and policy seed blocks overlap")
    worlds = []
    for i in range(n_worlds):
        w = {"world_id": f"{prefix}{i:04d}"}
        w.update({role: scenario_base + i * ns + j for j, role in enumerate(SCENARIO_ROLES)})
        w.update({role: policy_base + i * npol + j for j, role in enumerate(POLICY_ROLES)})
        worlds.append(w)
    return worlds


def expected_arms(benchmark_kwargs: dict) -> tuple:
    arms = ["loo_dependence_aware_mpc", "loo_conditional_independence_mpc", "no_signal_mpc"]
    if benchmark_kwargs.get("include_ambiguity_controller"):
        arms += list(PRIMARY_ARMS)
        if benchmark_kwargs.get("include_single_signal_controls"):
            arms += ["finite_set_minimax_molecular_only_mpc", "finite_set_minimax_mri_only_mpc"]
    return tuple(arms)


def check_arm_plan(benchmark_kwargs: dict) -> None:
    if benchmark_kwargs.get("filter_ranges") is not PF_PRIOR_INTEGRATED_V3:
        raise ValueError("integrated driver requires the V3 prior for every filter arm")
    arms = expected_arms(benchmark_kwargs)
    missing = [a for a in PRIMARY_ARMS + REQUIRED_CONTROL_ARMS if a not in arms]
    if missing:
        raise ValueError(f"arm plan lacks required primary/control arms: {missing}")
    if benchmark_kwargs.get("primary_contrast") != "minimax":
        raise ValueError("primary contrast must be minimax vs matched d=0")


def _is_real_benchmark(fn) -> bool:
    target = fn
    while target is not None:
        if getattr(target, "__name__", "") == "run_shared_policy_world":
            return True
        target = getattr(target, "__wrapped__", None) or getattr(target, "func", None)
    return False


def run_driver(worlds, *, mode, benchmark, family, patients_per_cohort, signal_parameters,
               model_parameters, settings, entries=None, config=None) -> dict:
    """Execute the integrated pipeline for all worlds and verify completeness.

    Returns an in-memory manifest; writes no files.
    """
    protocol = load_protocol(config)
    if mode == "evaluation":
        check_evaluation_gates(protocol)       # raises on the current config
    elif mode == "mechanics":
        if _is_real_benchmark(benchmark):
            raise PermissionError("mechanics mode refuses the real policy benchmark; supply a stub")
    else:
        raise ValueError("mode must be 'mechanics' or 'evaluation'")
    if getattr(settings, "stop_endpoint", None) != "observed_two_scan":
        raise ValueError("integrated v2 requires stop_endpoint='observed_two_scan'")
    worlds = [dict(w) for w in worlds]
    validate_development_schedule(worlds, entries=entries)
    records, inputs = [], []
    for w in worlds:
        prepared = prepare_synthetic_world(
            w, family=family, patients_per_cohort=patients_per_cohort,
            signal_parameters=signal_parameters, model_parameters=model_parameters,
            settings=settings, entries=entries,
        )
        check_arm_plan(prepared["benchmark_kwargs"])
        inputs.append({"world_id": w["world_id"], "world_parameters_sha256": prepared["world_parameters_sha256"]})
        records.append(execute_prepared_world(prepared, benchmark))
    ids = [r["world_id"] for r in records]
    if ids != [w["world_id"] for w in worlds]:
        raise RuntimeError("driver output is incomplete or out of order")
    return {
        "mode": mode, "family": family, "n_worlds": len(worlds),
        "prior_version": protocol.prior_version,
        "arm_plan": list(expected_arms(prepared["benchmark_kwargs"])),
        "open_evaluation_gates": list(protocol.open_gates),
        "inputs": inputs,
        "inputs_sha256": hashlib.sha256(json.dumps(inputs, sort_keys=True).encode()).hexdigest(),
        "records": records,
        "policy_outcomes_computed": mode == "evaluation",
    }
